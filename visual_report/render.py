"""Renderer 主模块：report-plan.json → 单文件离线 HTML。

确定性要求（ADR-001）：相同输入产生相同输出（不注入时间戳等易变内容）。
"""

import argparse
import html
import json
import sys
from pathlib import Path
from typing import Optional

from . import __version__
from .blocks import render_block
from .validate import ValidationError, validate_report_or_raise

_ASSETS_DIR = Path(__file__).resolve().parent.parent / "assets"

_RUNTIME_JS = """(function(){
  var btn = document.querySelector('.vr-backtop');
  if (btn) {
    window.addEventListener('scroll', function(){
      btn.classList.toggle('vr-visible', window.scrollY > 600);
    }, {passive:true});
  }
  // 架构图聚焦：点击节点只亮它和相邻边，再点取消（借鉴 archify 的 focus 交互）
  var focused = null;
  document.addEventListener('click', function(e){
    var node = e.target.closest('[data-node-id]');
    if (!node) return;
    var svg = node.closest('svg');
    if (!svg) return;
    var id = node.getAttribute('data-node-id');
    if (focused === id) { id = null; }
    focused = id;
    svg.querySelectorAll('[data-node-id]').forEach(function(el){
      el.classList.toggle('vr-diagram-dim', focused && el.getAttribute('data-node-id') !== focused);
    });
    svg.querySelectorAll('[data-edge-from]').forEach(function(el){
      var on = focused && (el.getAttribute('data-edge-from') === focused || el.getAttribute('data-edge-to') === focused);
      el.classList.toggle('vr-diagram-dim', focused && !on);
    });
  });
})();"""


def _esc(s) -> str:
    return html.escape(str(s), quote=True)


def _load_css(theme: str) -> str:
    base = (_ASSETS_DIR / "base.css").read_text(encoding="utf-8")
    theme_css = (_ASSETS_DIR / "themes" / f"{theme}.css").read_text(encoding="utf-8")
    return base + "\n/* ---- theme ---- */\n" + theme_css


def _render_section(sec: dict, base_dir: Optional[Path], meta: dict) -> str:
    layout = sec["layout"]
    sid = _esc(sec["id"])

    if layout == "hero":
        parts = [f'<span>{_esc(meta.get("author", ""))}</span>' if meta.get("author") else ""]
        if meta.get("date"):
            parts.append(f'<span>{_esc(meta["date"])}</span>')
        meta_line = "".join(parts)
        blocks = "".join(render_block(b, base_dir) for b in sec.get("blocks", []))
        return (
            f'<header id="{sid}" class="vr-hero"><div class="vr-hero-inner">'
            f"<h1>{_esc(sec['title'])}</h1>"
            + (f"<p>{_esc(sec['subtitle'])}</p>" if sec.get("subtitle") else "")
            + f'<div class="vr-hero-meta">{meta_line}</div>'
            + (f'<div style="margin-top:var(--space-5)">{blocks}</div>' if blocks else "")
            + "</div></header>"
        )

    cls = "vr-section"
    if sec.get("alt"):
        cls += " vr-section--alt"
    if layout == "conclusion":
        cls += " vr-section--conclusion"
    inner_cls = "vr-section-inner" + (" vr-section-inner--wide" if sec.get("wide") else "")

    head = ""
    if sec.get("kicker"):
        head += f'<span class="vr-section-kicker">{_esc(sec["kicker"])}</span>'
    head += f'<h2 class="vr-section-title">{_esc(sec["title"])}</h2>'
    if sec.get("subtitle"):
        head += f'<p class="vr-section-subtitle">{_esc(sec["subtitle"])}</p>'

    blocks = "".join(render_block(b, base_dir) for b in sec.get("blocks", []))
    return (
        f'<section id="{sid}" class="{cls}"><div class="{inner_cls}">'
        + (f"<header>{head}</header>" if head else "")
        + blocks
        + "</div></section>"
    )


def render_report(plan: dict, base_dir: Optional[Path] = None) -> str:
    """校验 + 渲染（按结构自动路由报告/幻灯片）。校验失败抛 ValidationError（不产出文件）。"""
    if "slides" in plan:
        from .deck import render_deck
        return render_deck(plan, base_dir)

    validate_report_or_raise(plan)

    meta = plan["meta"]
    theme = meta.get("theme", "minimal")

    sections = plan["sections"]

    # 目录（hero 之外的所有 section）
    toc = "".join(
        f'<a href="#{_esc(s["id"])}">{_esc(s["title"])}</a>'
        for s in sections
        if s["layout"] != "hero"
    )

    body = "".join(_render_section(s, base_dir, meta) for s in sections)
    footer_text = meta.get("footer") or f"Generated by visual-report v{__version__}"

    return f"""<!DOCTYPE html>
<html lang="{_esc(meta.get('lang', 'zh-CN'))}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="visual-report {_esc(__version__)}">
<title>{_esc(meta['title'])}</title>
<style>
{_load_css(theme)}
</style>
</head>
<body>
<nav class="vr-topbar">
  <span class="vr-title">{_esc(meta['title'])}</span>
  <div class="vr-toc">{toc}</div>
</nav>
{body}
<footer class="vr-footer">{_esc(footer_text)}</footer>
<a class="vr-backtop" href="#" aria-label="返回顶部">↑</a>
<script>
{_RUNTIME_JS}
</script>
</body>
</html>
"""


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="visual-report", description="report-plan.json → 单文件离线 HTML"
    )
    parser.add_argument("plan", help="report-plan.json 路径")
    parser.add_argument("-o", "--output", default="output/visual-report.html", help="输出 HTML 路径")
    parser.add_argument(
        "--base-dir", default=None,
        help="图片等相对资源的基准目录（默认取 plan 所在目录）",
    )
    args = parser.parse_args(argv)

    plan_path = Path(args.plan)
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    base_dir = Path(args.base_dir) if args.base_dir else plan_path.parent

    try:
        html_str = render_report(plan, base_dir)
    except ValidationError as e:
        print(f"✗ 校验失败，未生成文件：\n{e}", file=sys.stderr)
        return 2
    except (FileNotFoundError, ValueError) as e:
        print(f"✗ 渲染失败，未生成文件：{e}", file=sys.stderr)
        return 2

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html_str, encoding="utf-8")
    size_kb = out.stat().st_size / 1024
    print(f"✓ {out} ({size_kb:.0f} KB, theme={plan['meta'].get('theme', 'minimal')})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
